/**
 * Generates a compact star/constellation catalogue for the client from
 * d3-celestial's data files.
 *
 * d3-celestial is a full D3 sky-map library; we only need its underlying
 * catalogue, so this extracts the fields we use into flat arrays and commits
 * the result. That keeps the library itself a devDependency instead of a
 * runtime one, and cuts the bundled payload by roughly an order of magnitude.
 *
 * Run with: npm run build:catalog
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const DATA_DIR = join(dirname(require.resolve('d3-celestial/package.json')), 'data');
const OUT = join(dirname(fileURLToPath(import.meta.url)), '..', 'client', 'src', 'data', 'skyCatalog.json');

/** Naked-eye limit; also the limit of d3-celestial's smallest star file. */
const MAG_LIMIT = 6.0;
/** Only label stars bright enough to actually pick out. */
const NAME_MAG_LIMIT = 2.2;

const readJson = (name) => JSON.parse(readFileSync(join(DATA_DIR, name), 'utf8'));

/** d3-celestial stores RA as GeoJSON longitude in [-180, 180]. */
const toRa = (lon) => (lon < 0 ? lon + 360 : lon);
const r3 = (n) => Math.round(n * 1000) / 1000;
const r2 = (n) => Math.round(n * 100) / 100;

// --- Stars -----------------------------------------------------------------
const starData = readJson('stars.6.json');
const stars = starData.features
  .filter((f) => Number(f.properties.mag) <= MAG_LIMIT)
  .map((f) => ({
    hip: f.id,
    ra: toRa(f.geometry.coordinates[0]),
    dec: f.geometry.coordinates[1],
    mag: Number(f.properties.mag),
    bv: f.properties.bv === '' ? null : Number(f.properties.bv),
  }))
  // Brightest first, so a "render only the top N" cutoff stays meaningful.
  .sort((a, b) => a.mag - b.mag);

// --- Names for the brightest stars ----------------------------------------
const starNames = readJson('starnames.json');
const named = [];
for (const s of stars) {
  if (s.mag > NAME_MAG_LIMIT) continue;
  const entry = starNames[String(s.hip)];
  const name = entry?.name?.trim();
  if (!name) continue;
  named.push({ ra: r3(s.ra), dec: r3(s.dec), mag: r2(s.mag), name });
}

// --- Constellation stick figures ------------------------------------------
// Serpens ships as two features (Caput and Cauda) sharing the id "Ser", so
// group by id: one entry per constellation keeps ids unique for keying and
// yields a single centroid label for what is really one constellation.
const lineData = readJson('constellations.lines.json');
const linesById = new Map();
for (const f of lineData.features) {
  const geom = f.geometry;
  const parts = geom.type === 'MultiLineString' ? geom.coordinates : [geom.coordinates];
  const converted = parts.map((part) => part.map(([lon, lat]) => [r3(toRa(lon)), r3(lat)]));
  const existing = linesById.get(f.id);
  if (existing) existing.push(...converted);
  else linesById.set(f.id, converted);
}
const constellations = [...linesById].map(([id, lines]) => ({ id, lines }));

// --- Constellation names, placed at each figure's centroid ----------------
const constellationMeta = readJson('constellations.json');
const nameById = new Map(
  constellationMeta.features.map((f) => [f.id, (f.properties?.name ?? '').trim()])
);

const constellationLabels = constellations
  .map((c) => {
    const points = c.lines.flat();
    if (!points.length) return null;
    // Average in Cartesian space so figures spanning RA 0h don't average to
    // the opposite side of the sky.
    let x = 0;
    let y = 0;
    let z = 0;
    for (const [ra, dec] of points) {
      const a = (ra * Math.PI) / 180;
      const d = (dec * Math.PI) / 180;
      x += Math.cos(d) * Math.cos(a);
      y += Math.cos(d) * Math.sin(a);
      z += Math.sin(d);
    }
    const len = Math.hypot(x, y, z) || 1;
    x /= len;
    y /= len;
    z /= len;
    const ra = (Math.atan2(y, x) * 180) / Math.PI;
    return {
      id: c.id,
      name: nameById.get(c.id) || c.id,
      ra: r3(ra < 0 ? ra + 360 : ra),
      dec: r3((Math.asin(z) * 180) / Math.PI),
    };
  })
  .filter(Boolean);

const catalog = {
  attribution:
    'Star, constellation and name data derived from d3-celestial ' +
    '(https://github.com/ofrohn/d3-celestial), Copyright (c) 2015 Olaf Frohn, BSD-3-Clause. ' +
    'Generated by scripts/build-sky-catalog.mjs — do not edit by hand.',
  epoch: 'J2000',
  magnitudeLimit: MAG_LIMIT,
  // Flat parallel arrays: markedly smaller than an array of objects.
  stars: {
    ra: stars.map((s) => r3(s.ra)),
    dec: stars.map((s) => r3(s.dec)),
    mag: stars.map((s) => r2(s.mag)),
    // Colour index; 0 is a reasonable stand-in for the few stars lacking one.
    bv: stars.map((s) => (s.bv === null ? 0 : r2(s.bv))),
  },
  namedStars: named.sort((a, b) => a.mag - b.mag),
  constellations,
  constellationLabels,
};

writeFileSync(OUT, JSON.stringify(catalog));

const kb = (n) => `${(n / 1024).toFixed(1)} KB`;
console.log(`wrote ${OUT}`);
console.log(`  stars:               ${stars.length} (mag <= ${MAG_LIMIT})`);
console.log(`  named stars:         ${named.length} (mag <= ${NAME_MAG_LIMIT})`);
console.log(`  constellations:      ${constellations.length}`);
console.log(`  size:                ${kb(JSON.stringify(catalog).length)}`);
