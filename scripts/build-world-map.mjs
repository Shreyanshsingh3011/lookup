/**
 * Generates a compact world land-outline dataset for the ground-track map
 * from world-atlas's bundled 110m-resolution TopoJSON.
 *
 * world-atlas + topojson-client are full tools for working with TopoJSON; we
 * only need flat [lon, lat] polygon rings to draw, so this decodes once at
 * build time and commits the result as plain arrays. That keeps both
 * packages devDependencies instead of runtime ones. Interior rings (lake
 * holes, etc.) are dropped — at the scale this map renders at, they would be
 * invisible anyway.
 *
 * Run with: npm run build:worldmap
 */
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as topojson from 'topojson-client';

const require = createRequire(import.meta.url);
const OUT = join(dirname(fileURLToPath(import.meta.url)), '..', 'client', 'src', 'data', 'worldMap.json');

const topology = require('world-atlas/land-110m.json');
const geo = topojson.feature(topology, topology.objects.land);

const r2 = (n) => Math.round(n * 100) / 100;

/** Outer ring only (index 0) from each polygon; coordinates are [lon, lat]. */
const polygons = [];
for (const feature of geo.features) {
  const rings = feature.geometry.type === 'Polygon' ? [feature.geometry.coordinates] : feature.geometry.coordinates;
  for (const polygon of rings) {
    const outer = polygon[0];
    if (!outer || outer.length < 4) continue;
    polygons.push(outer.map(([lon, lat]) => [r2(lon), r2(lat)]));
  }
}

const data = {
  attribution:
    'Land outlines derived from Natural Earth via world-atlas (https://github.com/topojson/world-atlas), public domain. ' +
    'Generated by scripts/build-world-map.mjs — do not edit by hand.',
  resolution: '110m',
  polygons,
};

writeFileSync(OUT, JSON.stringify(data));

const kb = (n) => `${(n / 1024).toFixed(1)} KB`;
console.log(`wrote ${OUT}`);
console.log(`  polygons: ${polygons.length}`);
console.log(`  size:     ${kb(JSON.stringify(data).length)}`);
